"""`d2d experiment report`: run the pre-registered analysis end to end, write JSON, Markdown and
plots. All numbers come from the seeded simulator (no real users or production traffic)."""

from __future__ import annotations

import json
import time
from dataclasses import asdict
from pathlib import Path
from typing import Any

import numpy as np

from d2d.experiment.analyze import Plan, aa_simulator, analyze, decide, power_table
from d2d.experiment.simulate import DATA_LABEL, CaseTemplate, ExperimentConfig, simulate
from d2d.experiment.stats import aa_peeking


def run_report(
    cfg: ExperimentConfig,
    templates: list[CaseTemplate],
    *,
    aa_sims: int = 300,
    peeking_sims: int = 4000,
    with_hte: bool = True,
    seed: int | None = None,
) -> dict[str, Any]:
    seed = cfg.seed if seed is None else seed
    started = time.perf_counter()
    plan = Plan()
    pre = simulate(cfg, templates, "reviewer", seed=seed + 1000, effect_scale=0.0).cases
    reviewer = simulate(cfg, templates, "reviewer", seed=seed)
    case = simulate(cfg, templates, "case", seed=seed)
    srm = simulate(cfg, templates, "reviewer", seed=seed, srm_bug=True)
    obs = simulate(cfg, templates, "observational", seed=seed)

    primary = analyze(reviewer, "reviewer", plan)
    decision, reasons = decide(primary)
    out: dict[str, Any] = {
        "label": DATA_LABEL,
        "seed": seed,
        "templates": len(templates),
        "power": power_table(pre, cfg.reviewers, len(reviewer.cases)),
        "reviewer_design": primary,
        "decision": {"decision": decision, "reasons": reasons},
        "case_design": analyze(case, "case", plan),
        "srm_bug": analyze(srm, "reviewer", plan),
        "peeking": asdict(aa_peeking(sims=peeking_sims, seed=seed)),
        "aa_simulator": aa_simulator(cfg, templates, sims=aa_sims, seed=seed + 5000),
    }
    if with_hte:
        from d2d.experiment.hte import cross_fit_cate, validate_cate
        from d2d.experiment.observational import confounding_demo

        tau, lo, hi = cross_fit_cate(reviewer.cases, seed=seed)
        out["hte"] = validate_cate(reviewer.cases, tau, lo, hi)
        out["_cate"] = {"tau": tau, "true": reviewer.cases.true_cate}
        out["confounding"] = confounding_demo(obs.cases, seed=seed)
    else:
        from d2d.experiment.observational import confounding_demo

        out["confounding"] = confounding_demo(obs.cases, seed=seed, with_forest=False)
    out["runtime_seconds"] = time.perf_counter() - started
    return out


def _pp(x: float) -> str:
    return f"{100 * x:+.2f} pp"


def _ci(d: dict[str, Any]) -> str:
    return f"[{100 * d['ci_low']:+.2f}, {100 * d['ci_high']:+.2f}]"


def to_markdown(r: dict[str, Any]) -> str:
    rd, cd, sb = r["reviewer_design"], r["case_design"], r["srm_bug"]
    t = rd["truth"]
    lines = [
        "# Experiment results (simulated data)",
        "",
        f"> {r['label']}. Seed {r['seed']}; generated by `d2d experiment report`.",
        "",
        "## Power (pre-period A/A simulation)",
        "",
        f"Baseline conversion {r['power']['baseline_conversion']:.3f}, ICC "
        f"{r['power']['icc']:.3f} (after CUPED {r['power']['icc_after_cuped']:.3f}), "
        f"{r['power']['cases_per_reviewer']:.0f} cases per reviewer.",
        "",
        "| Randomization | CUPED | Cases per arm | Design effect | MDE (abs) | MDE (rel) |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for row in r["power"]["rows"]:
        lines.append(
            f"| {row['design']} | {'yes' if row['cuped'] else 'no'} | {row['n_per_arm']} | "
            f"{row['deff']:.2f} | {100 * row['mde']:.2f} pp | {100 * row['relative_mde']:.1f} % |"
        )
    lines += [
        "",
        "## Primary metric: action conversion",
        "",
        f"Ground truth: long-run ATE {_pp(t['ate_long_run'])}, ATE over the 28-day window "
        f"(with novelty) {_pp(t['ate_in_window'])}.",
        "",
        "| Design | Estimator | Estimate | 95% CI | p | SE |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for name, res in (("reviewer (primary)", rd), ("case (comparison)", cd)):
        for est, d in (
            ("difference in means", res["effects"]["conversion"]),
            ("CUPED", res["conversion_cuped"]),
            ("CUPED, weeks 3-4", res["novelty"]["late"]),
        ):
            lines.append(
                f"| {name} | {est} | {_pp(d['estimate'])} | {_ci(d)} | {d['p_value']:.2g} | "
                f"{100 * d['se']:.2f} pp |"
            )
    lines += [
        "",
        f"CUPED variance reduction: reviewer design {100 * rd['cuped_variance_reduction']:.1f} %, "
        f"case design {100 * cd['cuped_variance_reduction']:.1f} %.",
        f"Case-level randomization with spillover {cd['truth']['spillover']:.0%} "
        f"under-estimates the effect (see interference in the design doc).",
        "",
        "## All metrics (reviewer design) with multiple-testing correction",
        "",
        "| Metric | Role | Control | Treatment | Effect | 95% CI | p | Holm p | BH p |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    mt = rd["multiple_testing"]
    rows = [("conversion (CUPED)", "primary", rd["conversion_cuped"])] + [
        (m, role, rd["effects"][m])
        for m, role in (
            ("resolve_minutes", "secondary"),
            ("wrong_action", "guardrail"),
            ("false_escalation", "guardrail"),
        )
    ]
    for i, (m, role, d) in enumerate(rows):
        scale, unit = (1, " min") if m == "resolve_minutes" else (100, " pp")
        lines.append(
            f"| {m} | {role} | {scale * d['mean_control']:.3g} | {scale * d['mean_treatment']:.3g}"
            f" | {scale * d['estimate']:+.2f}{unit} | [{scale * d['ci_low']:+.2f}, "
            f"{scale * d['ci_high']:+.2f}] | {mt['p'][i]:.2g} | {mt['holm'][i]:.2g} | "
            f"{mt['bh'][i]:.2g} |"
        )
    lines += ["", "Guardrails (non-inferiority: upper 95% bound below margin):", ""]
    for m, g in rd["guardrails"].items():
        lines.append(
            f"- {m}: {_pp(g['estimate'])}, upper bound {_pp(g['ci_high'])}, margin "
            f"{_pp(g['margin'])} -> **{'pass' if g['pass'] else 'FAIL'}**"
        )
    lines += [
        "",
        "## Novelty (weekly CUPED effect, reviewer design)",
        "",
        "| Week | Estimate | 95% CI |",
        "|---|---:|---:|",
    ]
    for i, w in enumerate(rd["novelty"]["weekly"]):
        lines.append(f"| {i + 1} | {_pp(w['estimate'])} | {_ci(w)} |")
    seq = rd["sequential"]
    lines += [
        "",
        "## Sequential monitoring (O'Brien-Fleming, weekly looks)",
        "",
        "| Look (day) | Information | z | Boundary |",
        "|---|---:|---:|---:|",
    ]
    for d, i, z, b in zip(
        seq["look_days"], seq["information"], seq["z"], seq["bounds"], strict=True
    ):
        lines.append(f"| {d} | {i:.2f} | {z:.2f} | {b:.2f} |")
    lines += [
        "",
        f"Stopped at look: {seq['stopped_at_look'] or 'none (ran to completion)'}.",
        "",
        "## Peeking (A/A simulation)",
        "",
    ]
    pk = r["peeking"]
    lines += [
        f"{pk['sims']} A/A experiments, {pk['looks']} looks, alpha {pk['alpha']}: false-positive "
        f"rate {pk['fpr_fixed_horizon']:.3f} with one look, **{pk['fpr_naive_peeking']:.3f}** "
        f"when stopping at the first p < 0.05, {pk['fpr_obrien_fleming']:.3f} with O'Brien-Fleming "
        "boundaries.",
        "",
    ]
    aa = r["aa_simulator"]
    lines += [
        f"Simulator A/A ({aa['sims']} runs, Monte Carlo SE {aa['monte_carlo_se']:.3f}):",
        "",
        "| Design / SE | False-positive rate |",
        "|---|---:|",
    ]
    for k, v in aa["false_positive_rate"].items():
        lines.append(f"| {k} | {v:.3f} |")
    s = sb["srm"]
    lines += [
        "",
        "## SRM check on the injected logging bug",
        "",
        f"{sb['truth']['srm_dropped_cases']} slow treatment cases dropped. Chi-square on cases: "
        f"p = {s['cases']['p_value']:.2g}; per-reviewer Welch: p = "
        f"{s['per_reviewer']['p_value']:.2g} -> flagged: **{s['flagged']}**. Clean run flagged: "
        f"{rd['srm']['flagged']} (p = {rd['srm']['cases']['p_value']:.2g}).",
        f"Without the check, the buggy run would report a resolve-time effect of "
        f"{sb['effects']['resolve_minutes']['estimate']:+.2f} min vs "
        f"{rd['effects']['resolve_minutes']['estimate']:+.2f} min in the clean run.",
    ]
    if "hte" in r:
        h = r["hte"]
        lines += [
            "",
            "## Heterogeneous effects (causal forest, cross-fitted by reviewer)",
            "",
            f"Correlation with true CATE r = {h['pearson_r']:.3f}, RMSE {_pp(h['rmse'])}, "
            f"true CATE SD {_pp(h['true_sd'])}; {h['interval_level']:.0%} interval coverage "
            f"{h['interval_coverage']:.3f}; BLP calibration slope {h['blp_slope']:.2f} "
            f"(95% CI {h['blp_slope_ci'][0]:.2f} to {h['blp_slope_ci'][1]:.2f}).",
            "",
            "| Segment | Value | Cases | True | Estimated | Abs error |",
            "|---|---|---:|---:|---:|---:|",
        ]
        for seg, seg_rows in h["per_segment"].items():
            for row in seg_rows:
                lines.append(
                    f"| {seg} | {row['segment']} | {row['cases']} | {_pp(row['true'])} | "
                    f"{_pp(row['estimated'])} | {100 * row['abs_error']:.2f} pp |"
                )
        lines += [
            "",
            "| Calibration bin | Predicted | Observed (DiM) | 95% CI | True |",
            "|---:|---:|---:|---:|---:|",
        ]
        for row in h["calibration_bins"]:
            lines.append(
                f"| {row['bin']} | {_pp(row['predicted'])} | {_pp(row['observed'])} | "
                f"[{100 * row['observed_ci_low']:+.2f}, {100 * row['observed_ci_high']:+.2f}] | "
                f"{_pp(row['true'])} |"
            )
    cf = r["confounding"]
    lines += [
        "",
        "## Confounding demo (observational, reviewers choose)",
        "",
        "| Exposure | Truth | Estimator | Estimate | 95% CI | Covers truth |",
        "|---|---:|---|---:|---:|---|",
    ]
    for exp_name, row in cf["exposures"].items():
        for k in ("naive", "ols_adjusted", "aipw", "causal_forest"):
            if k in row:
                d = row[k]
                lines.append(
                    f"| {exp_name} | {_pp(row['truth'])} | {k} | {_pp(d['estimate'])} | {_ci(d)} | "
                    f"{'yes' if d['covers_truth'] else 'no'} |"
                )
    lines += [
        "",
        f"## Decision (pre-registered rule): **{r['decision']['decision']}**",
        "",
        *[f"- {x}" for x in r["decision"]["reasons"]],
        "",
    ]
    return "\n".join(lines)


def write_plots(r: dict[str, Any], out_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    rd, cd = r["reviewer_design"], r["case_design"]
    t = rd["truth"]
    note = "Simulated data"

    fig, ax = plt.subplots(figsize=(7, 3.6))
    items = [
        ("reviewer DiM", rd["effects"]["conversion"]),
        ("reviewer CUPED", rd["conversion_cuped"]),
        ("reviewer CUPED wk 3-4", rd["novelty"]["late"]),
        ("case DiM", cd["effects"]["conversion"]),
        ("case CUPED", cd["conversion_cuped"]),
    ]
    for i, (_, d) in enumerate(items):
        ax.errorbar(
            100 * d["estimate"],
            i,
            xerr=[[100 * (d["estimate"] - d["ci_low"])], [100 * (d["ci_high"] - d["estimate"])]],
            fmt="o",
            capsize=4,
        )
    ax.axvline(100 * t["ate_long_run"], ls="--", c="k", label="true long-run ATE")
    ax.axvline(100 * t["ate_in_window"], ls=":", c="gray", label="true ATE in window")
    ax.set_yticks(range(len(items)), [n for n, _ in items])
    ax.set_xlabel("Action conversion lift (pp), 95% CI")
    ax.set_title(f"Treatment effect by design and estimator ({note})")
    ax.legend(loc="lower right", fontsize=8)
    fig.tight_layout()
    paths.append(out_dir / "effects.png")
    fig.savefig(paths[-1], dpi=120)
    plt.close(fig)

    pk = r["peeking"]
    fig, ax = plt.subplots(figsize=(6, 3.4))
    looks = list(range(1, pk["looks"] + 1))
    ax.plot(looks, pk["fpr_naive_by_looks"], "o-", label="stop at first p < 0.05")
    ax.axhline(pk["alpha"], ls="--", c="k", label="alpha")
    ax.plot([pk["looks"]], [pk["fpr_obrien_fleming"]], "s", c="C2", label="O'Brien-Fleming")
    ax.set_xlabel("Number of looks")
    ax.set_ylabel("False-positive rate (A/A)")
    ax.set_title(f"Peeking inflates false positives ({note})")
    ax.legend(fontsize=8)
    fig.tight_layout()
    paths.append(out_dir / "peeking.png")
    fig.savefig(paths[-1], dpi=120)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 3.4))
    weeks = rd["novelty"]["weekly"]
    xs = np.arange(1, len(weeks) + 1)
    ax.errorbar(
        xs,
        [100 * w["estimate"] for w in weeks],
        yerr=[
            [100 * (w["estimate"] - w["ci_low"]) for w in weeks],
            [100 * (w["ci_high"] - w["estimate"]) for w in weeks],
        ],
        fmt="o-",
        capsize=4,
        label="estimate (CUPED)",
    )
    ax.axhline(100 * t["ate_long_run"], ls="--", c="k", label="true long-run ATE")
    ax.set_xticks(xs)
    ax.set_xlabel("Week")
    ax.set_ylabel("Lift (pp)")
    ax.set_title(f"Novelty effect decays ({note})")
    ax.legend(fontsize=8)
    fig.tight_layout()
    paths.append(out_dir / "novelty.png")
    fig.savefig(paths[-1], dpi=120)
    plt.close(fig)

    if "_cate" in r:
        tau, true = r["_cate"]["tau"], r["_cate"]["true"]
        h = r["hte"]
        fig, axes = plt.subplots(1, 2, figsize=(9, 3.8))
        idx = np.random.default_rng(0).choice(len(tau), min(3000, len(tau)), replace=False)
        axes[0].scatter(100 * true[idx], 100 * tau[idx], s=4, alpha=0.3)
        lim = [100 * min(true.min(), tau.min()), 100 * max(true.max(), tau.max())]
        axes[0].plot(lim, lim, "k--", lw=1)
        axes[0].set_xlabel("True CATE (pp)")
        axes[0].set_ylabel("Causal forest CATE (pp)")
        axes[0].set_title(f"Recovery, r = {h['pearson_r']:.2f}")
        cb = h["calibration_bins"]
        axes[1].errorbar(
            [100 * b["predicted"] for b in cb],
            [100 * b["observed"] for b in cb],
            yerr=[
                [100 * (b["observed"] - b["observed_ci_low"]) for b in cb],
                [100 * (b["observed_ci_high"] - b["observed"]) for b in cb],
            ],
            fmt="o",
            capsize=4,
            label="observed DiM",
        )
        axes[1].plot(
            [100 * b["predicted"] for b in cb], [100 * b["true"] for b in cb], "x", label="true"
        )
        lo_, hi_ = 100 * cb[0]["predicted"], 100 * cb[-1]["predicted"]
        axes[1].plot([lo_, hi_], [lo_, hi_], "k--", lw=1)
        axes[1].set_xlabel("Predicted CATE, bin mean (pp)")
        axes[1].set_ylabel("Effect in bin (pp)")
        axes[1].set_title("Calibration by predicted-effect quintile")
        axes[1].legend(fontsize=8)
        fig.suptitle(f"Causal forest vs simulator ground truth ({note})")
        fig.tight_layout()
        paths.append(out_dir / "cate.png")
        fig.savefig(paths[-1], dpi=120)
        plt.close(fig)

    cf = r["confounding"]["exposures"]
    fig, ax = plt.subplots(figsize=(7, 3.6))
    ests = [k for k in ("naive", "ols_adjusted", "aipw", "causal_forest") if k in cf["treated"]]
    width = 0.8 / len(ests)
    for j, k in enumerate(ests):
        for i, ex in enumerate(("treated", "history")):
            d = cf[ex][k]
            ax.errorbar(
                i + (j - (len(ests) - 1) / 2) * width,
                100 * d["estimate"],
                yerr=[
                    [100 * (d["estimate"] - d["ci_low"])],
                    [100 * (d["ci_high"] - d["estimate"])],
                ],
                fmt="o",
                c=f"C{j}",
                capsize=3,
                label=k if i == 0 else None,
            )
    for i, ex in enumerate(("treated", "history")):
        ax.hlines(100 * cf[ex]["truth"], i - 0.45, i + 0.45, colors="k", linestyles="--")
    ax.set_xticks([0, 1], ["opened suggestions\n(real effect)", "opened history\n(no effect)"])
    ax.set_ylabel("Estimated effect on conversion (pp)")
    ax.set_title(f"Observational data: naive vs adjusted; dashed = truth ({note})")
    ax.legend(fontsize=8)
    fig.tight_layout()
    paths.append(out_dir / "confounding.png")
    fig.savefig(paths[-1], dpi=120)
    plt.close(fig)
    return paths


def write_report(r: dict[str, Any], out_dir: Path, plots_dir: Path | None) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    data = {k: v for k, v in r.items() if not k.startswith("_")}
    paths = [out_dir / "results.json", out_dir / "results.md"]
    paths[0].write_text(json.dumps(data, indent=2, default=float) + "\n", "utf-8")
    paths[1].write_text(to_markdown(r), "utf-8")
    if plots_dir is not None:
        paths += write_plots(r, plots_dir)
    return paths
